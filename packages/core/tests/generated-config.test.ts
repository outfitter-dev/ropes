import { expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { managedAdapter } from "../src/adapters/managed.ts";
import { adaptersFor } from "../src/adapters/registry.ts";
import {
  CONFIG_PATH,
  GENERATED_PATH,
  POINTER,
  PRESET_PATH,
  rumdlPresetAdapter,
} from "../src/adapters/rumdl/preset.ts";
import { createCommands } from "../src/commands/registry.ts";
import { parseConfigTable } from "../src/config/parse.ts";
import { parsePlan } from "../src/contracts/parse.ts";
import { checkOne, fixOne } from "./one-file.ts";

const inRoot = async <T>(
  files: Readonly<Record<string, string>>,
  body: (root: string) => Promise<T>
): Promise<T> => {
  const root = await mkdtemp(path.join(tmpdir(), "ropes-gen-"));
  try {
    await Promise.all(
      Object.entries(files).map(([name, text]) =>
        Bun.write(path.join(root, name), text)
      )
    );
    return await body(root);
  } finally {
    await rm(root, { force: true, recursive: true });
  }
};

const text = (root: string, file: string): Promise<string> =>
  Bun.file(path.join(root, file)).text();

const TABLE = {
  MD007: { indent: 4 },
  global: { "extend-disable": ["MD024"] },
};

test("the generated config extends the preset and holds only the table", async () => {
  const adapter = rumdlPresetAdapter({ table: TABLE });
  await inRoot({}, async (root) => {
    await fixOne(adapter, { path: GENERATED_PATH, root });
    const written = await text(root, GENERATED_PATH);
    expect(written).toStartWith("# Generated by Ropes from `[tools.rumdl]`");
    expect(Bun.TOML.parse(written)).toEqual({
      ...TABLE,
      extends: "presets/rumdl.toml",
    });
    expect(
      path.posix.join(path.posix.dirname(GENERATED_PATH), "presets/rumdl.toml")
    ).toBe(PRESET_PATH);
  });
});

test("with no table the generated config is the extends line alone", async () => {
  await inRoot({}, async (root) => {
    await fixOne(rumdlPresetAdapter(), { path: GENERATED_PATH, root });
    expect(Bun.TOML.parse(await text(root, GENERATED_PATH))).toEqual({
      extends: "presets/rumdl.toml",
    });
  });
});

test("a changed table makes the generated config stale until it is rewritten", async () => {
  await inRoot({}, async (root) => {
    const input = { path: GENERATED_PATH, root };
    await fixOne(rumdlPresetAdapter(), input);
    const changed = rumdlPresetAdapter({ table: TABLE });
    const stale = await checkOne(changed, input);
    expect(stale.findings[0]?.message).toContain("rope doctor --fix");
    await fixOne(changed, input);
    expect(await checkOne(changed, input)).toEqual({
      findings: [],
      status: "passed",
    });
  });
});

test("the table cannot set extends, which is the chain itself", async () => {
  const adapter = rumdlPresetAdapter({ table: { extends: "other.toml" } });
  await inRoot({}, async (root) => {
    const outcome = await fixOne(adapter, { path: GENERATED_PATH, root });
    expect(outcome.findings[0]).toMatchObject({ fixable: false });
    expect(outcome.findings[0]?.message).toContain("Remove that key");
    expect(await Bun.file(path.join(root, GENERATED_PATH)).exists()).toBe(
      false
    );
  });
});

test("the bare line an older Cinch wrote becomes the marked pointer", async () => {
  const bare = `extends = "${GENERATED_PATH}"\n`;
  await inRoot({ [CONFIG_PATH]: bare }, async (root) => {
    const input = { path: CONFIG_PATH, root };
    expect(await checkOne(rumdlPresetAdapter(), input)).toMatchObject({
      findings: [{ fixable: true }],
    });
    await fixOne(rumdlPresetAdapter(), input);
    expect(await text(root, CONFIG_PATH)).toBe(POINTER);
  });
});

test("an authored config that extends the generated one is never touched", async () => {
  const own = `extends = "${GENERATED_PATH}"\n\n[MD007]\nindent = 8\n`;
  await inRoot({ [CONFIG_PATH]: own }, async (root) => {
    const input = { path: CONFIG_PATH, root };
    expect(await fixOne(rumdlPresetAdapter(), input)).toEqual({
      findings: [],
      status: "passed",
    });
    expect(await text(root, CONFIG_PATH)).toBe(own);
  });
});

test("a pointer someone added settings to is refused, not overwritten", async () => {
  const edited = `${POINTER}\n[MD007]\nindent = 8\n`;
  await inRoot({ [CONFIG_PATH]: edited }, async (root) => {
    const outcome = await fixOne(rumdlPresetAdapter(), {
      path: CONFIG_PATH,
      root,
    });
    expect(outcome.findings[0]).toMatchObject({ fixable: false });
    expect(outcome.findings[0]?.message).toContain(
      `${CONFIG_PATH} says Ropes generated it, but it holds more than Ropes wrote, so Ropes will not overwrite it.`
    );
    expect(await text(root, CONFIG_PATH)).toBe(edited);
  });
});

const REPO = { ".git/HEAD": "" };
const request = (root: string) => ({ cwd: root, json: true, paths: [] });

test("explain names the layer of each file in the chain", async () => {
  const files = { ...REPO, "rope.toml": "pilot = 0\n" };
  await inRoot(files, async (root) => {
    const { explain } = createCommands({ adapters: adaptersFor });
    const shown = await explain?.(request(root));
    const plan = parsePlan(JSON.parse(shown?.output ?? ""));
    const layers = plan.ok
      ? plan.value.paths.flatMap((entry) =>
          entry.layer === undefined ? [] : [[entry.path, entry.layer]]
        )
      : [];
    expect(layers).toEqual([
      [".ropes/configs/presets/rumdl.toml", "preset"],
      [".ropes/configs/rumdl.toml", "generated"],
      [CONFIG_PATH, "root"],
    ]);
    const human = await explain?.({ ...request(root), json: false });
    expect(human?.output).toContain(
      `.ropes/configs/rumdl.toml\n  layer: generated, generated from the Ropes config, and extends the preset`
    );
  });
});

test("a table for a tool Ropes generates nothing for is an error", async () => {
  const files = { ...REPO, "rope.toml": "pilot = 0\n[tools.nope]\na = 1\n" };
  await inRoot(files, async (root) => {
    const { check } = createCommands({ adapters: adaptersFor });
    const ran = await check?.(request(root));
    expect(ran?.exitCode).toBe(2);
    expect(ran?.error).toContain(
      'rope.toml: tools.nope: Ropes generates no config for "nope". It does for: rumdl.'
    );
  });
});

test("a table nothing reads because its preset is off is an error", async () => {
  const config =
    "pilot = 0\n[markdown]\npreset = false\n[tools.rumdl.MD007]\nindent = 4\n";
  await inRoot({ ...REPO, "rope.toml": config }, async (root) => {
    const { check } = createCommands({ adapters: adaptersFor });
    const ran = await check?.(request(root));
    expect(ran?.exitCode).toBe(2);
    expect(ran?.error).toContain("`markdown.preset = false`");
  });
});

test("an adapter says which table it copies, and a plain one says none", () => {
  expect(rumdlPresetAdapter().descriptor.table).toBe("rumdl");
  const plain = managedAdapter({
    enabledBy: "kept.enabled",
    files: [],
    id: "kept",
  });
  expect(plain.descriptor.table).toBeUndefined();
  expect(plain.descriptor.layers).toBeUndefined();
});

const ORIGIN = { file: "rope.toml", prefix: "" };

test("a table under tools is kept as the file states it", () => {
  const stated = Bun.TOML.parse(
    'pilot = 0\n[tools.lint.global]\nextend-disable = ["A1"]\n[tools.lint.A2]\nindent = 4\n'
  );
  const loaded = parseConfigTable(stated, ORIGIN);
  expect(loaded.ok && loaded.value.tools).toEqual({
    lint: { A2: { indent: 4 }, global: { "extend-disable": ["A1"] } },
  });
  const flat = parseConfigTable({ pilot: 0, tools: { lint: 1 } }, ORIGIN);
  expect(flat).toMatchObject({ error: { kind: "invalid" }, ok: false });
});
