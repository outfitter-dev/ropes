import { expect, test } from "bun:test";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { bunInstallAdapter } from "../src/adapters/bun-install/adapter.ts";
import { render as renderInstall } from "../src/adapters/bun-install/read.ts";
import { editorFileAdapter } from "../src/adapters/editorconfig/adapter.ts";
import { render as renderEditor } from "../src/adapters/editorconfig/render.ts";
import { generated, preset } from "../src/adapters/rumdl/generated.ts";
import { markdownPaths } from "../src/adapters/rumdl/paths.ts";
import { pointerFor, rootConfig } from "../src/adapters/rumdl/root-config.ts";
import { shippedHeader } from "../src/adapters/shipped.ts";
import { ROPES_MANAGED_DIR } from "../src/contracts/managed-config.ts";
import { renderFailureJson } from "../src/render/failure.ts";
import { fixtureGit, runEntry } from "./acceptance-repo.ts";

const paths = markdownPaths(ROPES_MANAGED_DIR);

const formerlyGenerated = (text: string): string =>
  text.replaceAll("Ropes", "Cinch").replaceAll("rope doctor", "cinch doctor");

test("generated setup uses Ropes ownership and executable instructions", async () => {
  const [generatedMarkdown, presetMarkdown] = await Promise.all([
    generated(),
    preset(),
  ]);
  const rendered = [
    pointerFor(paths),
    renderEditor({ indent_size: 2 }),
    renderInstall({ isolated: true }),
    shippedHeader("//"),
    generatedMarkdown.ok ? generatedMarkdown.text : generatedMarkdown.message,
    presetMarkdown.ok ? presetMarkdown.text : presetMarkdown.message,
  ];
  for (const text of rendered) {
    expect(text).toContain("Ropes");
    expect(text).toContain("rope doctor --fix");
    expect(text).not.toContain("Cinch");
  }
  const legacyPointer = formerlyGenerated(pointerFor(paths));
  const refreshed = await rootConfig(legacyPointer, {
    migrate: false,
    paths,
    root: "/unused",
  });
  expect(refreshed).toEqual({ ok: true, text: pointerFor(paths) });
  const authored = `${paths.extendsLine}\n# Team-owned settings\n[MD013]\nline-length = 91\n`;
  expect(
    await rootConfig(authored, { migrate: false, paths, root: "/unused" })
  ).toEqual({ ok: true, text: authored });
  const markedWithExtra = `${legacyPointer}\n[MD013]\nline-length = 91\n`;
  const modified = await rootConfig(markedWithExtra, {
    migrate: false,
    paths,
    root: "/unused",
  });
  expect(modified.ok).toBe(false);
});

test("old generated editor and install headers refresh while authored settings stay protected", async () => {
  const root = await mkdtemp(path.join(tmpdir(), "ropes-owned-headers-"));
  try {
    const editor = editorFileAdapter({ indent_size: 2 });
    const install = bunInstallAdapter({ isolated: true });
    const editorPath = path.join(root, ".editorconfig");
    const installPath = path.join(root, "bunfig.toml");
    await Bun.write(
      editorPath,
      formerlyGenerated(renderEditor({ indent_size: 4 }))
    );
    await Bun.write(
      installPath,
      formerlyGenerated(renderInstall({ isolated: false }))
    );
    const input = { package: ".", root };
    const fixedEditor = await editor.fix({
      ...input,
      paths: [".editorconfig"],
    });
    const fixedInstall = await install.fix({
      ...input,
      paths: ["bunfig.toml"],
    });
    expect(fixedEditor[0]?.status).toBe("fixed");
    expect(fixedInstall[0]?.status).toBe("fixed");
    expect(await readFile(editorPath, "utf-8")).toBe(
      renderEditor({ indent_size: 2 })
    );
    expect(await readFile(installPath, "utf-8")).toBe(
      renderInstall({ isolated: true })
    );
    const authoredEditor =
      "# Generated by Ropes users by hand\nroot = true\n[*]\nindent_size = 7\n";
    const authoredInstall =
      '# Team-owned install policy\n[install]\nlinker = "isolated"\ncache = false\n';
    await Bun.write(editorPath, authoredEditor);
    await Bun.write(installPath, authoredInstall);
    const refusedEditor = await editor.fix({
      ...input,
      paths: [".editorconfig"],
    });
    expect(refusedEditor[0]?.status).toBe("findings");
    await install.fix({ ...input, paths: ["bunfig.toml"] });
    expect(await readFile(editorPath, "utf-8")).toBe(authoredEditor);
    expect(await readFile(installPath, "utf-8")).toBe(authoredInstall);
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});

test("structured failures strip current and retired executable prefixes", () => {
  expect(
    JSON.parse(renderFailureJson("rope: first\ncinch: second"))
  ).toMatchObject({ error: { message: "first\nsecond" } });
});

test("everyday public output uses Ropes recovery advice and preserves retired filenames", async () => {
  const root = await mkdtemp(path.join(tmpdir(), "ropes-public-words-"));
  const entry = new URL("../../cli/src/cli.ts", import.meta.url);
  try {
    await Bun.write(
      path.join(root, "rope.toml"),
      `pilot = 0
[markdown]
enabled = false
preset = false
[toml]
enabled = false
[editor]
indent_size = 2
[rules]
enabled = true
`
    );
    await Bun.write(path.join(root, "README.md"), "# Words\n");
    await Bun.write(path.join(root, "tsconfig.json"), "{}\n");
    await fixtureGit(root, "init", "--quiet");
    await fixtureGit(root, "add", ".");
    await fixtureGit(root, "commit", "--quiet", "--message", "fixture");
    const repair = await runEntry(entry, ["doctor", "--fix"], root);
    expect(repair.exitCode).toBe(0);
    for (const command of ["explain", "check", "fix", "doctor"]) {
      // eslint-disable-next-line no-await-in-loop -- compare every public verb against the same quiet setup
      const result = await runEntry(entry, [command], root);
      expect(result.exitCode).toBe(0);
      expect(result.stdout).not.toContain("Cinch");
      expect(result.stdout).not.toContain("Run `cinch");
    }
    const plan = await runEntry(entry, ["explain", ".editorconfig"], root);
    expect(plan.exitCode).toBe(0);
    expect(plan.stdout).toContain("editor-file  ropes *");
    expect(plan.stdout.toLowerCase()).not.toContain("cinch");
    const structured = await runEntry(
      entry,
      ["explain", ".editorconfig", "--json"],
      root
    );
    expect(structured.exitCode).toBe(0);
    expect(structured.stdout).toContain('"tool": "ropes"');
    const diagnostic = await runEntry(entry, ["doctor"], root);
    expect(diagnostic.stdout).toContain("Run `rope rules adopt`");
    await rm(path.join(root, ".editorconfig"));
    const stopped = await runEntry(entry, ["fix"], root);
    expect(stopped.exitCode).toBe(1);
    expect(stopped.stdout).toContain("Ropes setup needs repair");
    expect(stopped.stdout).toContain("rope doctor --fix");
    await Bun.write(path.join(root, "cinch.toml"), "pilot = 0\n");
    const retired = await runEntry(entry, ["explain"], root);
    expect(retired.exitCode).toBe(2);
    expect(retired.stderr).toContain("cinch.toml");
    expect(retired.stderr).toContain("retired policy");
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});
