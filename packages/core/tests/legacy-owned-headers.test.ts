import { expect, test } from "bun:test";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { bunInstallAdapter } from "../src/adapters/bun-install/adapter.ts";
import { render as renderInstall } from "../src/adapters/bun-install/read.ts";
import { editorFileAdapter } from "../src/adapters/editorconfig/adapter.ts";
import { render as renderEditor } from "../src/adapters/editorconfig/render.ts";

test.each(["", ". Older generated wording."])(
  "legacy ownership header suffix %j remains repairable",
  async (suffix) => {
    const root = await mkdtemp(path.join(tmpdir(), "ropes-legacy-owned-"));
    try {
      const editor = editorFileAdapter({ indent_size: 2 });
      const install = bunInstallAdapter({ isolated: true });
      await Bun.write(
        path.join(root, ".editorconfig"),
        `# Generated by Cinch${suffix}\nroot = true\n[*]\nindent_size = 4\n`
      );
      await Bun.write(
        path.join(root, "bunfig.toml"),
        `# Generated by Cinch from \`[install]\`${suffix}\n[install]\nlinker = "hoisted"\n`
      );
      const [edited, installed] = await Promise.all([
        editor.fix({ package: ".", paths: [".editorconfig"], root }),
        install.fix({ package: ".", paths: ["bunfig.toml"], root }),
      ]);
      expect(edited[0]?.status).toBe("fixed");
      expect(installed[0]?.status).toBe("fixed");
      const [editorText, installText] = await Promise.all([
        readFile(path.join(root, ".editorconfig"), "utf-8"),
        readFile(path.join(root, "bunfig.toml"), "utf-8"),
      ]);
      expect(editorText).toBe(renderEditor({ indent_size: 2 }));
      expect(installText).toBe(renderInstall({ isolated: true }));
    } finally {
      await rm(root, { force: true, recursive: true });
    }
  }
);

test("short current ownership claims and extra native fields remain protected", async () => {
  const root = await mkdtemp(path.join(tmpdir(), "ropes-owned-safety-"));
  try {
    const editor = editorFileAdapter({ indent_size: 2 });
    const install = bunInstallAdapter({ isolated: true });
    const editorText =
      "# Generated by Ropes\nroot = true\n[*]\nindent_size = 7\n";
    await Bun.write(path.join(root, ".editorconfig"), editorText);
    const edited = await editor.fix({
      package: ".",
      paths: [".editorconfig"],
      root,
    });
    expect(edited[0]?.status).toBe("findings");
    expect(await readFile(path.join(root, ".editorconfig"), "utf-8")).toBe(
      editorText
    );
    for (const header of [
      "# Generated by Ropes from `[install]`",
      "# Generated by Cinch from `[install]`",
    ]) {
      const installText = `${header}\n[install]\nlinker = "hoisted"\n[test]\ncoverage = true\n`;
      // eslint-disable-next-line no-await-in-loop -- verify each ownership spelling cannot erase unrelated fields
      await Bun.write(path.join(root, "bunfig.toml"), installText);
      // eslint-disable-next-line no-await-in-loop -- compare each fixture independently
      const installed = await install.fix({
        package: ".",
        paths: ["bunfig.toml"],
        root,
      });
      expect(installed[0]?.status).toBe("findings");
      // eslint-disable-next-line no-await-in-loop -- verify bytes before replacing the fixture
      expect(await readFile(path.join(root, "bunfig.toml"), "utf-8")).toBe(
        installText
      );
    }
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});
