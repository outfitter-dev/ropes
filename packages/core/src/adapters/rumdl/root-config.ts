import path from "node:path";

import type { ToolTable } from "../../contracts/config.ts";
import type { Wanted } from "../managed.ts";
import { merge } from "./migrate/markdownlint/merge.ts";
import { extendsOf } from "./migrate/markdownlint/retire.ts";
import { carriedOver, gathered } from "./migrate/markdownlint/rules.ts";
import { LEGACY_PATHS, CONFIG_PATH, RUMDL_TABLE, standard } from "./paths.ts";
import type { MarkdownPaths } from "./paths.ts";

/** The first words of a root config Ropes wrote and still owns. */
const MARK = "# Generated by Ropes.";
const LEGACY_MARK = "# Generated by Cinch.";

/** The root config in generated mode: a pointer and nothing else. */
export const pointerFor = (
  paths: MarkdownPaths,
  command: "cinch" | "rope" = "rope"
): string => {
  const product = command === "cinch" ? "Cinch" : "Ropes";
  const mark = command === "cinch" ? LEGACY_MARK : MARK;
  return [
    `${mark} To change a Markdown rule, set it under \`[tools.${RUMDL_TABLE}]\``,
    `# in the ${product} config and run \`${command} doctor --fix\`. To write this file`,
    "# yourself, delete this comment and keep the `extends` line.",
    "",
    paths.extendsLine,
  ].join("\n");
};

export const POINTER = pointerFor(LEGACY_PATHS);

const OWN = `${CONFIG_PATH} is the repository's own, so Ropes will not overwrite it.`;

const SIBLINGS = ["rumdl.toml", ".config/rumdl.toml"];
const PYPROJECT = "pyproject.toml";

/** Every other file the engine could read its config from. */
export const ELSEWHERE = [...SIBLINGS, PYPROJECT];

const namesTool = (text: string): boolean => {
  try {
    const table: unknown = Bun.TOML.parse(text);
    if (typeof table !== "object" || table === null || !("tool" in table)) {
      return false;
    }
    const { tool } = table;
    return typeof tool === "object" && tool !== null && "rumdl" in tool;
  } catch {
    return false;
  }
};

/**
 * The engine reads its config from several places and uses only the first it
 * finds, so writing `CONFIG_PATH` beside another one would silently replace
 * the repository's settings. Returns the file that already holds them.
 */
export const configuredElsewhere = async (
  root: string
): Promise<string | null> => {
  const found = await Promise.all(
    SIBLINGS.map((name) => Bun.file(path.join(root, name)).exists())
  );
  const sibling = SIBLINGS.find((_, index) => found[index] === true);
  if (sibling !== undefined) {
    return sibling;
  }
  const project = Bun.file(path.join(root, PYPROJECT));
  const named = (await project.exists()) && namesTool(await project.text());
  return named ? PYPROJECT : null;
};

/**
 * A new config. It carries over what a config for the old Markdown linter
 * says, because the engine stops reading that one once this file exists.
 */
const fresh = async (run: Run): Promise<Wanted> => {
  const { command, root, table } = run;
  const paths = run.paths ?? LEGACY_PATHS;
  const other = await configuredElsewhere(root);
  if (other !== null) {
    return {
      message: `This repository configures Markdown in ${other}, and a new ${CONFIG_PATH} would hide it. Move those settings into ${CONFIG_PATH}, or set \`preset = false\` under \`[markdown]\` in the Ropes config.`,
      ok: false,
    };
  }
  const carried = await carriedOver(root, await standard(), command, table);
  // With nothing to carry over, the file stays a pointer Ropes owns.
  if (carried === null || (carried.ok && carried.text === "")) {
    return { ok: true, text: pointerFor(paths) };
  }
  return carried.ok
    ? { ok: true, text: `${paths.extendsLine}${carried.text}` }
    : carried;
};

/** Whether the file holds the `extends` line and no other setting. */
const onlyExtends = (text: string, paths: MarkdownPaths): boolean => {
  try {
    return Bun.deepEquals(Bun.TOML.parse(text), { extends: paths.generated });
  } catch {
    return false;
  }
};

/** Whether the file says Ropes generated it, whatever else it holds. */
export const isMarked = (current: string): boolean =>
  current.startsWith(MARK) || current.startsWith(LEGACY_MARK);

/**
 * Whether the root config is missing, or holds nothing a move could lose:
 * a pointer Ropes wrote, or the `extends` line alone with no comment beside
 * it, whatever its line endings or blank lines.
 */
export const isPointer = (
  current: string | null,
  paths: MarkdownPaths = LEGACY_PATHS
): boolean =>
  current === null ||
  (onlyExtends(current, paths) &&
    (isMarked(current) || !current.includes("#")));

/** What a run hands the root config's step. */
export interface Run {
  readonly root: string;
  /** See `StepInput.migrate`. */
  readonly migrate: boolean;
  /** The engine's executable. */
  readonly command?: string;
  /** What the Ropes config states for the engine. */
  readonly table?: ToolTable | undefined;
  readonly paths?: MarkdownPaths;
}

/**
 * A config that is already there is a person's, so it gets the `extends`
 * line and nothing else. Only `init`, which takes the repository over from
 * the old linter, also merges that linter's rules into it. An old config
 * Ropes cannot read is passed over, since the engine was not reading it
 * beside this file either.
 */
const withExtends = async (current: string, run: Run): Promise<Wanted> => {
  const { extendsLine } = run.paths ?? LEGACY_PATHS;
  if (!run.migrate) {
    return { ok: true, text: `${extendsLine}\n${current}` };
  }
  const carried = await gathered(
    run.root,
    await standard(),
    run.command,
    run.table
  );
  if (carried === null || (!carried.ok && carried.unknown !== true)) {
    return { ok: true, text: `${extendsLine}\n${current}` };
  }
  if (!carried.ok) {
    return carried;
  }
  const merged = merge({ ...carried, current });
  return merged.ok
    ? { ok: true, text: `${extendsLine}\n${merged.text}` }
    : merged;
};

const adopted = async (current: string, run: Run): Promise<Wanted> => {
  const added = await withExtends(current, run);
  const extendsLine = (run.paths ?? LEGACY_PATHS).extendsLine.trimEnd();
  return added.ok
    ? {
        ...added,
        why: `${OWN} It does not extend the config Ropes generates. Add \`${extendsLine}\` as its first line, or run \`rope doctor --fix\`, which adds it and changes nothing else.`,
      }
    : added;
};

/**
 * The root config must extend the generated one. A missing file becomes a
 * pointer Ropes owns. Any other file is the repository's own: one with no
 * `extends` gets the line at the top, where TOML needs a top-level key to
 * be, and nothing else in it is written outside `init`.
 */
export const rootConfig = async (
  current: string | null,
  run: Run
): Promise<Wanted> => {
  if (current === null) {
    return await fresh(run);
  }
  const paths = run.paths ?? LEGACY_PATHS;
  const pointer = pointerFor(paths);
  // The bare line is what Ropes wrote here before it marked its pointers.
  if (current === pointer || current === paths.extendsLine) {
    return { ok: true, text: pointer };
  }
  // Recognize a pointer that still suggests the retired repair command.
  if (current === pointerFor(paths, "cinch")) {
    return { ok: true, text: pointer };
  }
  if (isMarked(current)) {
    // Line endings or a reworded comment do not make the file a person's.
    if (onlyExtends(current, paths)) {
      return { ok: true, text: pointer };
    }
    if (
      paths.generated !== LEGACY_PATHS.generated &&
      onlyExtends(current, LEGACY_PATHS)
    ) {
      return {
        message: `${CONFIG_PATH} still points to the legacy managed directory. Change its \`extends\` line to \`${paths.extendsLine.trimEnd()}\` as part of the migration.`,
        ok: false,
      };
    }
    return {
      message: `${CONFIG_PATH} says Ropes generated it, but it holds more than Ropes wrote, so Ropes will not overwrite it. Move the settings to \`[tools.${RUMDL_TABLE}]\` in the Ropes config and delete this file, or delete its first comment to make the file your own.`,
      ok: false,
    };
  }
  let found: unknown;
  try {
    found = extendsOf(current);
  } catch {
    return {
      message: `${OWN} It is not valid TOML, so Ropes cannot tell whether it extends ${paths.generated}.`,
      ok: false,
    };
  }
  if (found === paths.generated) {
    return { ok: true, text: current };
  }
  if (found === undefined) {
    return await adopted(current, run);
  }
  return {
    message: `${OWN} It extends ${JSON.stringify(found)}, not the config Ropes generates. Change the line to \`${paths.extendsLine.trimEnd()}\`, or set \`preset = false\` under \`[markdown]\` in the Ropes config.`,
    ok: false,
  };
};
