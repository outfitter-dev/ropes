import { expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { MANAGED_RULE, managedAdapter } from "../src/adapters/managed.ts";
import {
  CONFIG_PATH,
  GENERATED_PATH,
  POINTER,
  PRESET_PATH,
  rumdlPresetAdapter,
} from "../src/adapters/rumdl/preset.ts";
import { createCommands } from "../src/commands/registry.ts";
import { checkOne, fixOne } from "./one-file.ts";

const SOURCE = new URL("../presets/rumdl.toml", import.meta.url);

const inRoot = async <T>(
  files: Readonly<Record<string, string>>,
  body: (root: string) => Promise<T>
): Promise<T> => {
  const root = await mkdtemp(path.join(tmpdir(), "cinch-kept-"));
  try {
    await Promise.all(
      Object.entries(files).map(([name, text]) =>
        Bun.write(path.join(root, name), text)
      )
    );
    return await body(root);
  } finally {
    await rm(root, { force: true, recursive: true });
  }
};

const text = (root: string, file: string): Promise<string> =>
  Bun.file(path.join(root, file)).text();

const fixed = managedAdapter({
  enabledBy: "kept.enabled",
  files: [
    {
      path: "kept.txt",
      want: () => Promise.resolve({ ok: true, text: "A\n" }),
    },
  ],
  id: "kept",
});

test("a kept file is planned by its exact path, and needs no engine", async () => {
  expect(fixed.descriptor.owns).toEqual(["kept.txt"]);
  expect(fixed.descriptor.extensions).toEqual([]);
  expect(await fixed.probe()).toEqual({ available: true });
});

test("check reports a missing kept file and writes nothing", async () => {
  await inRoot({}, async (root) => {
    const outcome = await checkOne(fixed, { path: "kept.txt", root });
    expect(outcome.status).toBe("findings");
    expect(outcome.findings).toMatchObject([
      { fixable: true, path: "kept.txt", rule: MANAGED_RULE, source: "kept" },
    ]);
    expect(outcome.findings[0]?.message).toContain("is missing");
    expect(await Bun.file(path.join(root, "kept.txt")).exists()).toBe(false);
  });
});

test("check reports an edited kept file, fix rewrites it, and a second fix passes", async () => {
  await inRoot({ "kept.txt": "edited\n" }, async (root) => {
    const input = { path: "kept.txt", root };
    const before = await checkOne(fixed, input);
    expect(before.findings[0]?.message).toContain("differs");
    expect(await fixOne(fixed, input)).toMatchObject({ status: "fixed" });
    expect(await text(root, "kept.txt")).toBe("A\n");
    expect(await fixOne(fixed, input)).toEqual({
      findings: [],
      status: "passed",
    });
    expect(await checkOne(fixed, input)).toEqual({
      findings: [],
      status: "passed",
    });
  });
});

test("a path the adapter does not keep is incomplete, never passed", async () => {
  await inRoot({}, async (root) => {
    const outcome = await checkOne(fixed, { path: "other.txt", root });
    expect(outcome.status).toBe("incomplete");
  });
});

const preset = rumdlPresetAdapter();

test("the Markdown preset is copied with a header that says who keeps it", async () => {
  await inRoot({}, async (root) => {
    expect(preset.descriptor.enabledBy).toBe("markdown.preset");
    expect(await fixOne(preset, { path: PRESET_PATH, root })).toMatchObject({
      status: "fixed",
    });
    const copy = await text(root, PRESET_PATH);
    expect(copy).toStartWith("# Managed by Cinch. Do not edit this file");
    expect(copy).toEndWith(await Bun.file(SOURCE).text());
  });
});

test("a repository with no config of its own gets a pointer Cinch owns", async () => {
  await inRoot({}, async (root) => {
    await fixOne(preset, { path: CONFIG_PATH, root });
    const pointer = await text(root, CONFIG_PATH);
    expect(pointer).toBe(POINTER);
    expect(pointer).toStartWith("# Generated by Cinch.");
    expect(Bun.TOML.parse(pointer)).toEqual({ extends: GENERATED_PATH });
  });
});

test("a config with no extends line gets one at the top and keeps the rest", async () => {
  const own = "[MD007]\nindent = 4\n";
  await inRoot({ [CONFIG_PATH]: own }, async (root) => {
    const input = { path: CONFIG_PATH, root };
    const before = await checkOne(preset, input);
    expect(before).toMatchObject({ findings: [{ fixable: true }] });
    expect(before.findings[0]?.message).toContain(
      `Add \`extends = "${GENERATED_PATH}"\` as its first line`
    );
    await fixOne(preset, input);
    const written = await text(root, CONFIG_PATH);
    expect(written).toBe(`extends = "${GENERATED_PATH}"\n\n${own}`);
    expect(Bun.TOML.parse(written)).toEqual({
      MD007: { indent: 4 },
      extends: GENERATED_PATH,
    });
    expect(await checkOne(preset, input)).toEqual({
      findings: [],
      status: "passed",
    });
  });
});

test("a config that extends something else is reported and left alone", async () => {
  const own = 'extends = "elsewhere.toml"\n';
  await inRoot({ [CONFIG_PATH]: own }, async (root) => {
    const outcome = await fixOne(preset, { path: CONFIG_PATH, root });
    expect(outcome.status).toBe("findings");
    expect(outcome.findings[0]).toMatchObject({ fixable: false });
    expect(outcome.findings[0]?.message).toContain("preset = false");
    expect(outcome.findings[0]?.message).toContain(
      `${CONFIG_PATH} is the repository's own, so Cinch will not overwrite it.`
    );
    expect(outcome.findings[0]?.message).toContain(
      `\`extends = "${GENERATED_PATH}"\``
    );
    expect(await text(root, CONFIG_PATH)).toBe(own);
  });
});

test("a config that is not valid TOML is reported and left alone", async () => {
  const own = "extends = \n";
  await inRoot({ [CONFIG_PATH]: own }, async (root) => {
    const outcome = await fixOne(preset, { path: CONFIG_PATH, root });
    expect(outcome.findings[0]?.message).toContain("not valid TOML");
    expect(await text(root, CONFIG_PATH)).toBe(own);
  });
});

test("a dry run shows a kept file doctor would write, and doctor --fix writes it", async () => {
  const files = { ".git/HEAD": "", "cinch.toml": "pilot = 0\n" };
  await inRoot(files, async (root) => {
    const { check, doctor } = createCommands({ adapters: () => [fixed] });
    const request = { cwd: root, json: false, paths: [] };
    expect(await check?.(request)).toMatchObject({ exitCode: 1 });
    const preview = await doctor?.({ ...request, dryRun: true, fix: true });
    expect(preview?.output).toContain("+++ b/kept.txt\n@@ -0,0 +1,1 @@\n+A");
    expect(await Bun.file(path.join(root, "kept.txt")).exists()).toBe(false);
    expect(await doctor?.({ ...request, fix: true })).toMatchObject({
      exitCode: 0,
    });
    expect(await text(root, "kept.txt")).toBe("A\n");
    expect(await check?.(request)).toMatchObject({ exitCode: 0 });
  });
});
