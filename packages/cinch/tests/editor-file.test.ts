import { afterEach, beforeEach, expect, test } from "bun:test";
import { mkdir, mkdtemp, realpath, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { EDITOR_PATH } from "../src/adapters/editorconfig/adapter.ts";
import { render } from "../src/adapters/editorconfig/render.ts";
import { adaptersFor } from "../src/adapters/registry.ts";
import type { CommandRequest } from "../src/commands/command.ts";
import { createCommands } from "../src/commands/registry.ts";
import { parseConfigTable } from "../src/config/parse.ts";
import { DoctorReportSchema } from "../src/contracts/doctor.ts";
import { parsePlan } from "../src/contracts/parse.ts";

/** Everything else is off, so no test here needs an engine. */
const QUIET =
  "pilot = 0\n[markdown]\nenabled = false\npreset = false\n[toml]\nenabled = false\n";
const EDITOR = `${QUIET}[editor]\nindent_style = "space"\nindent_size = 2\n`;
const HEAD =
  "# Generated by Cinch from `[editor]` in the Cinch config. Do not edit this file:\n# `cinch doctor --fix` rewrites it.\nroot = true\n";

let root = "";
beforeEach(async () => {
  root = await realpath(await mkdtemp(path.join(tmpdir(), "cinch-editor-")));
  await mkdir(path.join(root, ".git"));
});
afterEach(async () => {
  await rm(root, { force: true, recursive: true });
});

const put = (file: string, text: string): Promise<number> =>
  Bun.write(path.join(root, file), text);
const kept = (): Promise<string> =>
  Bun.file(path.join(root, EDITOR_PATH)).text();

const run = (verb: string, request: Partial<CommandRequest> = {}) => {
  const command = createCommands({ adapters: adaptersFor })[verb];
  if (!command) {
    throw new Error(`no command ${verb}`);
  }
  return command({ cwd: root, json: true, paths: [], ...request });
};

const exit = async (...asked: Parameters<typeof run>): Promise<number> => {
  const response = await run(...asked);
  return response.exitCode;
};

const messages = async (): Promise<string[]> => {
  const response = await run("doctor");
  const report = DoctorReportSchema.parse(JSON.parse(response.output ?? ""));
  return report.result.steps.flatMap((step) =>
    step.findings.map((finding) => finding.message)
  );
};

const first = async (): Promise<string> => {
  const [message = ""] = await messages();
  return message;
};

test("the file lists the base facts, then one section for each glob", () => {
  const text = render({
    charset: "utf-8",
    end_of_line: "lf",
    final_newline: true,
    indent_size: 2,
    indent_style: "space",
    line_width: 80,
    overrides: [
      { files: ["Makefile", "*.mk"], indent_style: "tab" },
      { files: ["*.md"], trim_trailing_whitespace: false },
      { files: ["*.txt"] },
    ],
    trim_trailing_whitespace: true,
  });
  expect(text).toBe(
    `${HEAD}
[*]
charset = utf-8
indent_style = space
indent_size = 2
end_of_line = lf
insert_final_newline = true
trim_trailing_whitespace = true
max_line_length = 80

[Makefile]
indent_style = tab

[*.mk]
indent_style = tab

[*.md]
trim_trailing_whitespace = false
`
  );
});

test("the config rejects a fact it does not know and a glob that breaks a header", () => {
  const origin = { file: "cinch.toml", prefix: "" };
  const unknown = parseConfigTable(
    { editor: { tab_width: 4 }, pilot: 0 },
    origin
  );
  expect(unknown.ok).toBe(false);
  const glob = parseConfigTable(
    { editor: { overrides: [{ files: ["a]\n[b"] }] }, pilot: 0 },
    origin
  );
  expect(glob.ok).toBe(false);
});

test("changing a fact and running doctor --fix changes the file", async () => {
  await put("cinch.toml", EDITOR);
  expect(await exit("doctor")).toBe(1);
  expect(await exit("doctor", { fix: true })).toBe(0);
  expect(await kept()).toBe(
    `${HEAD}\n[*]\nindent_style = space\nindent_size = 2\n`
  );
  await put("cinch.toml", EDITOR.replace("indent_size = 2", "indent_size = 4"));
  expect(await messages()).toEqual([
    "This file differs from `[editor]` in the Cinch config. Make the change there, then run `cinch doctor --fix`.",
  ]);
  await run("doctor", { fix: true });
  expect(await kept()).toContain("indent_size = 4");
});

test("a hand edit is a finding that says where to make the change, and check sees it", async () => {
  await put("cinch.toml", EDITOR);
  await run("doctor", { fix: true });
  await put(EDITOR_PATH, `${await kept()}\n[*.go]\nindent_style = tab\n`);
  expect(await first()).toContain("Make the change there");
  expect(await exit("check")).toBe(1);
  expect(await exit("fix")).toBe(1);
  expect(await kept()).toContain("[*.go]");
});

test("a file a person wrote is never overwritten", async () => {
  const mine = "root = true\n\n[*]\nindent_style = tab\n";
  await put("cinch.toml", EDITOR);
  await put(EDITOR_PATH, mine);
  expect(await exit("doctor", { fix: true })).toBe(1);
  expect(await kept()).toBe(mine);
  expect(await first()).toStartWith("This file was written by hand");
});

test("without the table, the file is not Cinch's and is left alone", async () => {
  const mine = "root = true\n";
  await put("cinch.toml", QUIET);
  await put(EDITOR_PATH, mine);
  expect(await exit("doctor", { fix: true })).toBe(0);
  expect(await kept()).toBe(mine);
  const shown = await run("explain", { paths: [EDITOR_PATH] });
  const plan = parsePlan(JSON.parse(shown.output ?? ""));
  expect(plan.ok && plan.value.paths[0]?.steps).toEqual([]);
});

test("an excluded editor file is an unusable setup, not a clean one", async () => {
  await put(
    "cinch.toml",
    EDITOR.replace("pilot = 0", 'pilot = 0\nexclude = [".editorconfig"]')
  );
  const repaired = await run("doctor", { fix: true });
  expect(repaired.exitCode).toBe(2);
  expect(repaired.error).toContain(
    "the Cinch config leaves .editorconfig out (`exclude` in cinch.toml), so Cinch cannot keep it."
  );
  expect(await exit("fix")).toBe(2);
  expect(await Bun.file(path.join(root, EDITOR_PATH)).exists()).toBe(false);
});

test("init writes the editor file a config that is already there asks for", async () => {
  await put("cinch.toml", EDITOR);
  expect(await exit("init", { yes: true })).toBe(0);
  expect(await kept()).toContain("indent_size = 2");
  expect(await exit("doctor")).toBe(0);
});
