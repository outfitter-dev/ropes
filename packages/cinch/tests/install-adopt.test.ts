import { expect, test } from "bun:test";
import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { adaptersFor } from "../src/adapters/registry.ts";
import { createCommands } from "../src/commands/registry.ts";

test("preset adopt install previews, applies and then stays idempotent through the public command", async () => {
  const root = await mkdtemp(path.join(tmpdir(), "ropes-install-adopt-"));
  const commands = createCommands({ adapters: adaptersFor });
  try {
    await mkdir(path.join(root, ".git"));
    const config =
      "pilot = 0\n[markdown]\nenabled = false\npreset = false\n[toml]\nenabled = false\n";
    const bunfig =
      '[install]\nlinker = "isolated"\nminimumReleaseAge = 604800\n';
    await Promise.all([
      Bun.write(path.join(root, "rope.toml"), config),
      Bun.write(path.join(root, "bunfig.toml"), bunfig),
    ]);
    const request = {
      action: "adopt",
      cwd: root,
      json: true,
      paths: ["install"],
    };
    const preview = await commands.preset?.(request);
    expect(preview?.exitCode).toBe(0);
    expect(preview?.output).toContain("[install]");
    expect(await Bun.file(path.join(root, "rope.toml")).text()).toBe(config);
    expect(await Bun.file(path.join(root, "bunfig.toml")).text()).toBe(bunfig);
    const adopted = await commands.preset?.({ ...request, yes: true });
    expect(adopted?.exitCode).toBe(0);
    const written = await Bun.file(path.join(root, "rope.toml")).text();
    expect(written).toContain("[install]");
    expect(await Bun.file(path.join(root, "bunfig.toml")).text()).toStartWith(
      "# Generated by Cinch from `[install]`"
    );
    const again = await commands.preset?.({ ...request, yes: true });
    expect(again?.exitCode).toBe(0);
    expect(await Bun.file(path.join(root, "rope.toml")).text()).toBe(written);
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});
