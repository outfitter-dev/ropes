import { afterEach, beforeEach, expect, test } from "bun:test";
import { mkdir, mkdtemp, realpath, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { adaptersFor } from "../src/adapters/registry.ts";
import type { CommandRequest } from "../src/commands/command.ts";
import { createCommands } from "../src/commands/registry.ts";
import { parseConfigTable } from "../src/config/parse.ts";
import { PresetReportSchema } from "../src/contracts/preset.ts";

const PRESETS = ".outfitter/configs/presets";
const SHIPPED = path.join(import.meta.dir, "..", "presets");
const FILES = ["oxfmt.ts", "oxlint.ts", "tsconfig.json"];
const ON =
  "[lint]\npreset = true\n[format]\npreset = true\n[typescript]\npreset = true\n";

const commands = createCommands({ adapters: adaptersFor });

let root = "";
beforeEach(async () => {
  root = await realpath(await mkdtemp(path.join(tmpdir(), "cinch-shipped-")));
  await mkdir(path.join(root, ".git"));
});
afterEach(async () => {
  await rm(root, { force: true, recursive: true });
});

const run = (verb: string, request: Partial<CommandRequest> = {}) => {
  const command = commands[verb];
  if (!command) {
    throw new Error(`no command ${verb}`);
  }
  return command({ cwd: root, json: true, paths: [], ...request });
};

const config = (text: string): Promise<number> =>
  Bun.write(path.join(root, "cinch.toml"), `pilot = 0\n${text}`);

/** Puts a package at one version where the repository would import it. */
const install = (name: string, version: string): Promise<number> =>
  Bun.write(
    path.join(root, "node_modules", name, "package.json"),
    JSON.stringify({ name, version })
  );

const exists = (file: string): Promise<boolean> =>
  Bun.file(path.join(root, PRESETS, file)).exists();

const statesOf = (output: string | undefined): string[] =>
  PresetReportSchema.parse(JSON.parse(output ?? "null")).presets.flatMap(
    (preset) => preset.files.map((file) => `${preset.name} ${file.state}`)
  );

test("the lint, format and TypeScript presets are off until asked for", async () => {
  await config("");
  const listed = await run("preset");
  expect(statesOf(listed.output)).toEqual([
    "markdown missing",
    "markdown missing",
    "markdown missing",
    "lint off",
    "format off",
    "typescript off",
  ]);
  await run("doctor", { fix: true });
  const kept = await Promise.all(FILES.map(exists));
  expect(kept).toEqual([false, false, false]);
});

test("adding a preset that is off says which setting switches it on", async () => {
  await config("");
  const added = await run("preset", { action: "add", paths: ["lint"] });
  expect(added.exitCode).toBe(2);
  expect(added.error).toBe(
    "cinch: the lint preset is off until the Cinch config asks for it. Set `preset = true` under `[lint]`, then run this again."
  );
  expect(await exists("oxlint.ts")).toBe(false);
});

test("an update that names no preset passes over the ones that are off", async () => {
  await config("[lint]\npreset = true\n");
  await install("ultracite", "8.1.1");
  const updated = await run("preset", { action: "update" });
  expect(updated.exitCode).toBe(0);
  expect(await exists("oxlint.ts")).toBe(true);
  expect(await exists("oxfmt.ts")).toBe(false);
  // The Markdown preset is on by default, so the update wrote it too.
  expect(await exists("rumdl.toml")).toBe(true);
  const named = await run("preset", { action: "update", paths: ["format"] });
  expect(named.exitCode).toBe(2);
  expect(named.error).toContain("the format preset is off");
});

test("a preset the config asks for is written with a header, then current", async () => {
  await config(ON);
  await install("ultracite", "8.1.1");
  const before = await run("check");
  expect(before.exitCode).toBe(1);
  const fixed = await run("doctor", { fix: true });
  expect(fixed.exitCode).toBe(0);
  const texts = await Promise.all(
    FILES.map(async (file) => ({
      kept: await Bun.file(path.join(root, PRESETS, file)).text(),
      shipped: await Bun.file(path.join(SHIPPED, file)).text(),
    }))
  );
  for (const { kept, shipped } of texts) {
    expect(kept).toStartWith("// Managed by Cinch. Do not edit this file");
    expect(kept).toEndWith(`\n\n${shipped}`);
  }
  const listed = await run("preset");
  expect(statesOf(listed.output).slice(3)).toEqual([
    "lint current",
    "format current",
    "typescript current",
  ]);
});

test("one preset can be on while the others stay off", async () => {
  await config("[typescript]\npreset = true\n");
  await run("doctor", { fix: true });
  const kept = await Promise.all(FILES.map(exists));
  expect(kept).toEqual([false, false, true]);
});

test("a hand edit to a kept preset is a finding that doctor repairs", async () => {
  await config(ON);
  await run("doctor", { fix: true });
  const file = path.join(root, PRESETS, "tsconfig.json");
  await Bun.write(file, "{}\n");
  const checked = await run("check");
  expect(checked.exitCode).toBe(1);
  expect(checked.output).toContain("cinch/managed-file");
  await run("doctor", { fix: true });
  expect(await Bun.file(file).text()).toContain('"strict": true');
});

test("the preset tables take no key they do not know", () => {
  const origin = { file: "cinch.toml", prefix: "" };
  const stated = parseConfigTable(
    { lint: { preset: true }, pilot: 0, typescript: { preset: false } },
    origin
  );
  const keys = stated.ok
    ? stated.value.settings.map((setting) => [setting.key, setting.value])
    : [];
  expect(keys).toContainEqual(["lint.preset", true]);
  expect(keys).toContainEqual(["typescript.preset", false]);
  const unknown = parseConfigTable(
    { format: { check: true }, pilot: 0 },
    origin
  );
  expect(unknown).toMatchObject({ error: { kind: "invalid" }, ok: false });
});
