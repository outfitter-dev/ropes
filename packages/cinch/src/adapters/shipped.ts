import type { Adapter } from "./adapter.ts";
import { managedAdapter } from "./managed.ts";

export interface ShippedOptions {
  readonly id: string;
  /** The name a person uses for the preset. */
  readonly preset: string;
  /** The policy key that switches the preset on when it is `true`. */
  readonly enabledBy: string;
  /** Where the copy sits in a repository, root-relative. */
  readonly path: string;
  /** The preset as this Cinch ships it. */
  readonly source: URL;
  /** What starts a line comment in the file's format. */
  readonly comment: string;
}

/** The lines that say whose the copy is, in the file's own comment form. */
export const shippedHeader = (comment: string): string =>
  [
    `${comment} Managed by Cinch. Do not edit this file: \`cinch doctor --fix\` rewrites it.`,
    `${comment} Put this repository's own settings in the config that extends it.`,
    "",
    "",
  ].join("\n");

/**
 * Keeps one copy of a preset this Cinch ships, for a tool whose own config
 * extends the copy. The preset is off until the Cinch config asks for it,
 * since not every repository uses the tool.
 */
export const shippedPreset = (options: ShippedOptions): Adapter =>
  managedAdapter({
    enabledBy: options.enabledBy,
    files: [
      {
        layer: "preset",
        path: options.path,
        want: async () => ({
          ok: true,
          text: `${shippedHeader(options.comment)}${await Bun.file(options.source).text()}`,
        }),
      },
    ],
    id: options.id,
    optIn: true,
    preset: options.preset,
  });
