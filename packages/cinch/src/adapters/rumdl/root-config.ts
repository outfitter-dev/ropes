import path from "node:path";

import type { ToolTable } from "../../contracts/config.ts";
import type { Wanted } from "../managed.ts";
import { merge } from "./migrate/markdownlint/merge.ts";
import { extendsOf } from "./migrate/markdownlint/retire.ts";
import { carriedOver, gathered } from "./migrate/markdownlint/rules.ts";
import {
  CONFIG_PATH,
  EXTENDS,
  GENERATED_PATH,
  RUMDL_TABLE,
  standard,
} from "./paths.ts";

/** The first words of a root config Cinch wrote and still owns. */
const MARK = "# Generated by Cinch.";

/** The root config in generated mode: a pointer and nothing else. */
export const POINTER = [
  `${MARK} To change a Markdown rule, set it under \`[tools.${RUMDL_TABLE}]\``,
  "# in the Cinch config and run `cinch doctor --fix`. To write this file",
  "# yourself, delete this comment and keep the `extends` line.",
  "",
  EXTENDS,
].join("\n");

const OWN = `${CONFIG_PATH} is the repository's own, so Cinch will not overwrite it.`;

const SIBLINGS = ["rumdl.toml", ".config/rumdl.toml"];
const PYPROJECT = "pyproject.toml";

const namesTool = (text: string): boolean => {
  try {
    const table: unknown = Bun.TOML.parse(text);
    if (typeof table !== "object" || table === null || !("tool" in table)) {
      return false;
    }
    const { tool } = table;
    return typeof tool === "object" && tool !== null && "rumdl" in tool;
  } catch {
    return false;
  }
};

/**
 * The engine reads its config from several places and uses only the first it
 * finds, so writing `CONFIG_PATH` beside another one would silently replace
 * the repository's settings. Returns the file that already holds them.
 */
const configuredElsewhere = async (root: string): Promise<string | null> => {
  const found = await Promise.all(
    SIBLINGS.map((name) => Bun.file(path.join(root, name)).exists())
  );
  const sibling = SIBLINGS.find((_, index) => found[index] === true);
  if (sibling !== undefined) {
    return sibling;
  }
  const project = Bun.file(path.join(root, PYPROJECT));
  const named = (await project.exists()) && namesTool(await project.text());
  return named ? PYPROJECT : null;
};

/**
 * A new config. It carries over what a config for the old Markdown linter
 * says, because the engine stops reading that one once this file exists.
 */
const fresh = async (run: Run): Promise<Wanted> => {
  const { command, root, table } = run;
  const other = await configuredElsewhere(root);
  if (other !== null) {
    return {
      message: `This repository configures Markdown in ${other}, and a new ${CONFIG_PATH} would hide it. Move those settings into ${CONFIG_PATH}, or set \`preset = false\` under \`[markdown]\` in the Cinch config.`,
      ok: false,
    };
  }
  const carried = await carriedOver(root, await standard(), command, table);
  // With nothing to carry over, the file stays a pointer Cinch owns.
  if (carried === null || (carried.ok && carried.text === "")) {
    return { ok: true, text: POINTER };
  }
  return carried.ok ? { ok: true, text: `${EXTENDS}${carried.text}` } : carried;
};

const ADD = `${OWN} It does not extend the config Cinch generates. Add \`${EXTENDS.trimEnd()}\` as its first line, or run \`cinch doctor --fix\`, which adds it and changes nothing else.`;

/** Whether the file holds the `extends` line and no other setting. */
const onlyExtends = (text: string): boolean => {
  try {
    return Bun.deepEquals(Bun.TOML.parse(text), { extends: GENERATED_PATH });
  } catch {
    return false;
  }
};

/** What a run hands the root config's step. */
export interface Run {
  readonly root: string;
  /** See `StepInput.migrate`. */
  readonly migrate: boolean;
  /** The engine's executable. */
  readonly command?: string;
  /** What the Cinch config states for the engine. */
  readonly table?: ToolTable | undefined;
}

/**
 * A config that is already there is a person's, so it gets the `extends`
 * line and nothing else. Only `init`, which takes the repository over from
 * the old linter, also merges that linter's rules into it. An old config
 * Cinch cannot read is passed over, since the engine was not reading it
 * beside this file either.
 */
const withExtends = async (current: string, run: Run): Promise<Wanted> => {
  if (!run.migrate) {
    return { ok: true, text: `${EXTENDS}\n${current}` };
  }
  const carried = await gathered(
    run.root,
    await standard(),
    run.command,
    run.table
  );
  if (carried === null || (!carried.ok && carried.unknown !== true)) {
    return { ok: true, text: `${EXTENDS}\n${current}` };
  }
  if (!carried.ok) {
    return carried;
  }
  const merged = merge({ ...carried, current });
  return merged.ok ? { ok: true, text: `${EXTENDS}\n${merged.text}` } : merged;
};

const adopted = async (current: string, run: Run): Promise<Wanted> => {
  const added = await withExtends(current, run);
  return added.ok ? { ...added, why: ADD } : added;
};

/**
 * The root config must extend the generated one. A missing file becomes a
 * pointer Cinch owns. Any other file is the repository's own: one with no
 * `extends` gets the line at the top, where TOML needs a top-level key to
 * be, and nothing else in it is written outside `init`.
 */
export const rootConfig = async (
  current: string | null,
  run: Run
): Promise<Wanted> => {
  if (current === null) {
    return await fresh(run);
  }
  // The bare line is what Cinch wrote here before it marked its pointers.
  if (current === POINTER || current === EXTENDS) {
    return { ok: true, text: POINTER };
  }
  if (current.startsWith(MARK)) {
    // Line endings or a reworded comment do not make the file a person's.
    if (onlyExtends(current)) {
      return { ok: true, text: POINTER };
    }
    return {
      message: `${CONFIG_PATH} says Cinch generated it, but it holds more than Cinch wrote, so Cinch will not overwrite it. Move the settings to \`[tools.${RUMDL_TABLE}]\` in the Cinch config and delete this file, or delete its first comment to make the file your own.`,
      ok: false,
    };
  }
  let found: unknown;
  try {
    found = extendsOf(current);
  } catch {
    return {
      message: `${OWN} It is not valid TOML, so Cinch cannot tell whether it extends ${GENERATED_PATH}.`,
      ok: false,
    };
  }
  if (found === GENERATED_PATH) {
    return { ok: true, text: current };
  }
  if (found === undefined) {
    return await adopted(current, run);
  }
  return {
    message: `${OWN} It extends ${JSON.stringify(found)}, not the config Cinch generates. Change the line to \`${EXTENDS.trimEnd()}\`, or set \`preset = false\` under \`[markdown]\` in the Cinch config.`,
    ok: false,
  };
};
