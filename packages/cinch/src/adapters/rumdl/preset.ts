import path from "node:path";

import type { Adapter } from "../adapter.ts";
import { managedAdapter } from "../managed.ts";
import type { Wanted } from "../managed.ts";
import { chosenFiles } from "./markdownlint-files.ts";
import { carriedOver } from "./markdownlint.ts";

/** The copy of the standard that Cinch keeps in a repository. */
export const PRESET_PATH = ".outfitter/configs/rumdl.toml";
/** The repository's own rumdl config. It extends the copy. */
export const CONFIG_PATH = ".rumdl.toml";

const SOURCE = new URL("../../../presets/rumdl.toml", import.meta.url);

const HEADER = [
  "# Managed by Cinch. Do not edit this file: `cinch fix` rewrites it.",
  `# Put this repository's own choices in \`${CONFIG_PATH}\`, after its`,
  "# `extends` line.",
  "",
  "",
].join("\n");

const EXTENDS = `extends = ${JSON.stringify(PRESET_PATH)}\n`;

const standard = (): Promise<string> => Bun.file(SOURCE).text();

const preset = async (): Promise<Wanted> => ({
  ok: true,
  text: `${HEADER}${await standard()}`,
});

const extendsOf = (text: string): unknown => {
  const table: unknown = Bun.TOML.parse(text);
  return typeof table === "object" && table !== null && "extends" in table
    ? table.extends
    : undefined;
};

const SIBLINGS = ["rumdl.toml", ".config/rumdl.toml"];
const PYPROJECT = "pyproject.toml";

const namesTool = (text: string): boolean => {
  try {
    const table: unknown = Bun.TOML.parse(text);
    if (typeof table !== "object" || table === null || !("tool" in table)) {
      return false;
    }
    const { tool } = table;
    return typeof tool === "object" && tool !== null && "rumdl" in tool;
  } catch {
    return false;
  }
};

/**
 * The engine reads its config from several places and uses only the first it
 * finds, so writing `CONFIG_PATH` beside another one would silently replace
 * the repository's settings. Returns the file that already holds them.
 */
const configuredElsewhere = async (root: string): Promise<string | null> => {
  const found = await Promise.all(
    SIBLINGS.map((name) => Bun.file(path.join(root, name)).exists())
  );
  const sibling = SIBLINGS.find((_, index) => found[index] === true);
  if (sibling !== undefined) {
    return sibling;
  }
  const project = Bun.file(path.join(root, PYPROJECT));
  const named = (await project.exists()) && namesTool(await project.text());
  return named ? PYPROJECT : null;
};

/**
 * A new config. It carries over what a config for the old Markdown linter
 * says, because the engine stops reading that one once this file exists.
 */
const fresh = async (root: string, command?: string): Promise<Wanted> => {
  const other = await configuredElsewhere(root);
  if (other !== null) {
    return {
      message: `This repository configures Markdown in ${other}, and a new ${CONFIG_PATH} would hide it. Move those settings into ${CONFIG_PATH}, or set \`preset = false\` under \`[markdown]\` in the Cinch config.`,
      ok: false,
    };
  }
  const carried = await carriedOver(root, await standard(), command);
  if (carried === null) {
    return { ok: true, text: EXTENDS };
  }
  return carried.ok ? { ok: true, text: `${EXTENDS}${carried.text}` } : carried;
};

/**
 * The repository's config must extend the copy. A missing file is written,
 * and a file with no `extends` gets the line at the top, where TOML needs a
 * top-level key to be. A file that extends something else is left alone.
 */
const config = async (
  current: string | null,
  root: string,
  command?: string
): Promise<Wanted> => {
  if (current === null) {
    return await fresh(root, command);
  }
  let found: unknown;
  try {
    found = extendsOf(current);
  } catch {
    return {
      message: "This file is not valid TOML, so Cinch cannot read it.",
      ok: false,
    };
  }
  if (found === PRESET_PATH) {
    return { ok: true, text: current };
  }
  if (found === undefined) {
    return { ok: true, text: `${EXTENDS}\n${current}` };
  }
  return {
    message: `This file extends ${JSON.stringify(found)}, not the Markdown standard at ${PRESET_PATH}. Change the line, or set \`preset = false\` under \`[markdown]\` in the Cinch config.`,
    ok: false,
  };
};

/**
 * Keeps the shared Markdown standard in a repository: a copy of the preset,
 * and the line in the repository's own rumdl config that extends it.
 */
export const rumdlPresetAdapter = (
  options: {
    /** The engine's executable. */
    readonly command?: string;
  } = {}
): Adapter =>
  managedAdapter({
    enabledBy: "markdown.preset",
    files: [
      { path: PRESET_PATH, want: preset },
      {
        path: CONFIG_PATH,
        want: (current, root) => config(current, root, options.command),
      },
    ],
    id: "rumdl-preset",
    inherits: chosenFiles,
    preset: "markdown",
  });
