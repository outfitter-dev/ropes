import { z } from "zod";

import { InstallSchema, ageSeconds } from "../../contracts/install.ts";
import type { InstallSettings } from "../../contracts/install.ts";

export const BUNFIG = "bunfig.toml";
export const MARK = "# Generated by Cinch from `[install]`";

const Native = z.strictObject({
  install: z
    .strictObject({
      linker: z.enum(["isolated", "hoisted"]).optional(),
      minimumReleaseAge: z
        .number()
        .int()
        .nonnegative()
        .max(Number.MAX_SAFE_INTEGER)
        .optional(),
      minimumReleaseAgeExcludes: z.array(z.string().min(1)).optional(),
    })
    .optional(),
});

/** Only files that fit the neutral policy can be replaced by generated text. */
export const readInstall = (text: string): InstallSettings => {
  const parsed = Native.parse(Bun.TOML.parse(text)).install ?? {};
  return InstallSchema.parse({
    ...(parsed.linker === undefined
      ? {}
      : { isolated: parsed.linker === "isolated" }),
    ...(parsed.minimumReleaseAge === undefined
      ? {}
      : { minimum_release_age: `${parsed.minimumReleaseAge} seconds` }),
    ...(parsed.minimumReleaseAgeExcludes === undefined
      ? {}
      : { release_age_exempt: parsed.minimumReleaseAgeExcludes }),
  });
};

/** A canonical native table, shared by generation and equivalence checks. */
export const nativeInstall = (settings: InstallSettings) => ({
  ...(settings.isolated === undefined
    ? {}
    : { linker: settings.isolated ? "isolated" : "hoisted" }),
  ...(settings.minimum_release_age === undefined
    ? {}
    : { minimumReleaseAge: ageSeconds(settings.minimum_release_age) }),
  ...(settings.release_age_exempt === undefined
    ? {}
    : { minimumReleaseAgeExcludes: settings.release_age_exempt }),
});

/** Authored files can keep unrelated native settings while sharing these facts. */
export const authoredAgrees = (
  text: string,
  settings: InstallSettings
): boolean => {
  const Root = z.looseObject({
    install: z.record(z.string(), z.unknown()).optional(),
  });
  const own = Root.parse(Bun.TOML.parse(text)).install ?? {};
  return Object.entries(nativeInstall(settings)).every(([key, value]) =>
    Bun.deepEquals(own[key], value, true)
  );
};

export const render = (settings: InstallSettings): string =>
  [
    `${MARK} in the Cinch config.`,
    "# Change the table, then run `cinch doctor --fix`.",
    "[install]",
    ...Object.entries(nativeInstall(settings)).map(
      ([key, value]) => `${key} = ${JSON.stringify(value)}`
    ),
    "",
  ].join("\n");

export const tableOf = (settings: InstallSettings, prefix = ""): string[] => [
  "# Install facts carried over from bunfig.toml by Cinch.",
  `[${prefix}install]`,
  ...Object.entries(settings).map(
    ([key, value]) => `${key} = ${JSON.stringify(value)}`
  ),
  "",
];
